"""Regenerates crates/parsec-orbit-loader-windows/src/exports.rs from the system bcrypt.dll.

The loader replaces bcrypt.dll, so it has to export every function the real
DLL exports; otherwise a module in the client process fails to resolve an
import when it starts. Instead of hand-writing the prototypes, this script
emits one naked thunk per export. Each thunk points at a slot in `SLOTS` and
jumps into `resolve_stub`, which forwards the call to the real implementation
in %SystemRoot%\\System32\\bcrypt.dll.

Run it after a Windows update if bcrypt.dll gained or lost exports:

    python scripts/gen-bcrypt-exports.py

Requires: pip install pefile
"""

import pathlib
import sys

import pefile

SYSTEM_BCRYPT = pathlib.Path(r"C:\Windows\System32\bcrypt.dll")
OUTPUT = (
    pathlib.Path(__file__).resolve().parent.parent
    / "crates"
    / "parsec-orbit-loader-windows"
    / "src"
    / "exports.rs"
)


def main() -> int:
    if not SYSTEM_BCRYPT.is_file():
        print(f"{SYSTEM_BCRYPT} not found; run this on Windows", file=sys.stderr)
        return 1

    exports = [
        symbol.name.decode()
        for symbol in pefile.PE(str(SYSTEM_BCRYPT)).DIRECTORY_ENTRY_EXPORT.symbols
        if symbol.name
    ]
    if not exports:
        print("no named exports found", file=sys.stderr)
        return 1

    lines = [
        "// @generated by scripts/gen-bcrypt-exports.py - do not edit by hand.",
        "//",
        f"// {len(exports)} named exports mirrored from {SYSTEM_BCRYPT}.",
        "//",
        "// Each thunk loads the address of its slot, then jumps into the shared",
        "// resolver stub, which fills the slot on first use and forwards the call",
        "// to the real bcrypt.dll.",
        "",
        "use core::arch::naked_asm;",
        "use core::sync::atomic::AtomicUsize;",
        "",
        f"pub static SLOTS: [AtomicUsize; {len(exports)}] =",
        f"    [const {{ AtomicUsize::new(0) }}; {len(exports)}];",
        "",
        f"pub static NAMES: [&str; {len(exports)}] = [",
    ]
    lines += [f'    "{name}",' for name in exports]
    lines += ["];", ""]
    for index, name in enumerate(exports):
        lines += [
            "#[unsafe(naked)]",
            "#[no_mangle]",
            f"pub unsafe extern \"system\" fn {name}() -> usize {{",
            "    naked_asm!(",
            "        \"lea rax, [rip + {slots} + {offset}]\",",
            "        \"jmp {resolve}\",",
            "        slots = sym SLOTS,",
            f"        offset = const {index * 8}usize,",
            "        resolve = sym crate::resolve_stub,",
            "    );",
            "}",
            "",
        ]
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    # newline="\n" keeps the generated file LF-only on every platform.
    OUTPUT.write_text("\n".join(lines), encoding="ascii", newline="\n")
    print(f"wrote {OUTPUT} with {len(exports)} thunks")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
